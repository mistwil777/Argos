-- ============================================
-- VIEWS
-- ============================================
CREATE OR REPLACE VIEW pending_items_view AS
SELECT i.id, i.title, i.source_type, i.importance, i.keywords, i.created_at, i.url
FROM items i
WHERE i.classification_status = 'pending'
ORDER BY i.created_at DESC;

CREATE OR REPLACE VIEW unindexed_items_view AS
SELECT i.id, i.title, i.summary, i.digest_json, i.created_at
FROM items i
WHERE i.rag_indexed = FALSE
  AND i.classification_status = 'classified'
  AND i.digest_json IS NOT NULL
ORDER BY i.created_at DESC;

